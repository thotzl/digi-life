//! Diet classes (TCK-202): the one source of every carnivory threshold. The predator flag, the "raptor" name, the
//! trainer's diet target, biting and photosynthesis all read the class; the frontend's labels read the generated
//! `bindings/diet.ts`. The thresholds are model constants (like the organ classification), not config: changing them
//! changes stored phenotypes (`is_predator`, names).

/// Carnivory at or above this value: carnivore (hunts meat only, predator flag, "raptor" name).
pub const CARNIVORE_MIN: f32 = 0.6;
/// Carnivory below this value: herbivore (grazes plants only, never bites, may photosynthesise); in between: omnivore.
pub const HERBIVORE_MAX: f32 = 0.4;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DietClass {
    Herbivore,
    Omnivore,
    Carnivore,
}

impl DietClass {
    pub fn from_carnivory(carnivory: f32) -> Self {
        if carnivory >= CARNIVORE_MIN {
            DietClass::Carnivore
        } else if carnivory >= HERBIVORE_MAX {
            DietClass::Omnivore
        } else {
            DietClass::Herbivore
        }
    }

    /// Predator flag of the phenotype (`CreaturePhenotype::is_predator`) and the "raptor" name.
    pub fn is_predator(self) -> bool {
        self == DietClass::Carnivore
    }

    /// Omnivores and carnivores bite in the Ocean (`sim::systems::bite`).
    pub fn bites(self) -> bool {
        self != DietClass::Herbivore
    }

    /// Only herbivores can photosynthesise (`sim::systems::metabolize::EnergyModifier::Photosynthesis`).
    pub fn photosynthesises(self) -> bool {
        self == DietClass::Herbivore
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_diet_class_thresholds() {
        assert_eq!(DietClass::from_carnivory(0.39), DietClass::Herbivore);
        assert_eq!(DietClass::from_carnivory(0.4), DietClass::Omnivore);
        assert_eq!(DietClass::from_carnivory(0.59), DietClass::Omnivore);
        assert_eq!(DietClass::from_carnivory(0.6), DietClass::Carnivore);
    }

    /// Writes the thresholds for the frontend labels (`bindings/diet.ts`, committed; CI checks drift).
    #[test]
    fn export_diet_thresholds() {
        let ts = format!(
            "// Generated by `cargo test` from src/biology/diet.rs. Do not edit this file manually.\n\n/** Carnivory at or above which a creature is a carnivore (predator). */\nexport const CARNIVORE_MIN = {:?};\n/** Carnivory below which a creature is a herbivore; in between: omnivore. */\nexport const HERBIVORE_MAX = {:?};\n",
            CARNIVORE_MIN, HERBIVORE_MAX
        );
        crate::biology::genome::write_binding("diet.ts", &ts);
    }
}
